// Миксин для шагов визарда: реактивно сообщает в стор текущую валидность шага.
// Индикатор шагов строит по ней подсветку и кликабельность, поэтому «зелёный»
// шаг означает «заполнен правильно прямо сейчас», а не «когда-то прошёл
// валидацию по "Далее"»: если вернуться и стереть обязательные поля, шаг
// сразу перестаёт быть валидным, и шаги за ним блокируются.
//
// Валидация «тихая» (silent): считает валидность, не показывая сообщения
// об ошибках — ошибки по-прежнему подсвечивает только настоящая валидация
// по кнопке «Далее».
export default {
  methods: {
    validateFormSilently() {
      if (!this.$refs.form) return Promise.resolve(false);
      return this.$refs.form.validate({silent: true});
    },
    reportStepValidity(step, valid) {
      // «?.»: юнит-тесты монтируют шаги изолированно, без стора.
      this.$store?.commit?.('setStepValidity', {step, valid: Boolean(valid)});
    },
  },
};
